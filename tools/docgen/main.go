// Command docgen writes docs/reference/features.md and reason-codes.md from
// the feature registry and the built-in rule set, so the docs cannot drift
// from the code. CI runs it and fails if the output differs.
//
//	go run ./tools/docgen -out docs/reference
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/iamsuriyan/doorkeep/internal/scoring"
	"github.com/iamsuriyan/doorkeep/internal/scoring/rules"
)

var groupTitle = map[scoring.Group]string{
	scoring.GroupProfile: "Privacy profile (informational, never risk)", scoring.GroupAuto: "Automation markers",
	scoring.GroupFP: "Fingerprint consistency", scoring.GroupBehaviour: "Behaviour (aggregates only)",
	scoring.GroupEnv: "Environment", scoring.GroupTiming: "Timing truth", scoring.GroupNet: "Network and headers (server-side)",
	scoring.GroupVelocity: "Velocity",
}

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func main() {
	out := flag.String("out", "docs/reference", "output directory")
	flag.Parse()
	if err := os.MkdirAll(*out, 0o755); err != nil {
		panic(err)
	}

	var b strings.Builder
	b.WriteString("# Feature reference\n\n<!-- Generated by tools/docgen. Do not edit. -->\n\n")
	b.WriteString("Every event stores these bucketed features (never raw signals). Rules address them as `group.name`. Unknown values are NaN or empty and never fire a rule. \"Model\" marks features the learned model may use.\n")
	var groups []scoring.Group
	seen := map[scoring.Group]bool{}
	for _, d := range scoring.Registry() {
		if !seen[d.Group] {
			seen[d.Group] = true
			groups = append(groups, d.Group)
		}
	}
	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n\n| Key | Kind | Model | Description |\n|---|---|---|---|\n", groupTitle[g])
		for _, d := range scoring.Registry() {
			if d.Group != g {
				continue
			}
			kind := d.Kind.String()
			if len(d.Buckets) > 0 {
				kind += ": " + strings.Join(d.Buckets, ", ")
			}
			if len(d.Values) > 0 {
				kind += ": " + strings.Join(d.Values, ", ")
			}
			model := ""
			if d.Model {
				model = "yes"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", d.Key(), esc(kind), model, esc(d.Desc))
		}
	}
	must(os.WriteFile(filepath.Join(*out, "features.md"), []byte(b.String()), 0o644))

	set, err := rules.Builtin()
	must(err)
	rs := set.Rules()
	sort.SliceStable(rs, func(i, j int) bool { return rs[i].Weight > rs[j].Weight })
	b.Reset()
	b.WriteString("# Reason codes\n\n<!-- Generated by tools/docgen. Do not edit. -->\n\n")
	b.WriteString("Built-in rules, by weight. Weights add up to a 0 to 100 risk (default: challenge at 35, block at 75). A floor rule is proof rather than evidence: risk never drops below its weight, and no challenge can clear it. Sites can change mode and weight per rule, or add their own, in the dashboard.\n\n")
	b.WriteString("| Code | Weight | Floor | Description | When | Unless |\n|---|---|---|---|---|---|\n")
	for _, r := range rs {
		floor := ""
		if r.Floor {
			floor = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %+d | %s | %s | `%s` | %s |\n", r.ID, r.Weight, floor, esc(r.Description), esc(r.When), unless(r.Unless))
	}
	b.WriteString("\nOther codes you may see on events:\n\n| Code | Meaning |\n|---|---|\n")
	for _, x := range [][2]string{
		{"ALLOWLIST_<KIND>", "An allow-list entry matched (ip, cidr, asn, country, fp, ua_regex, crawler, tor); risk forced to 0"},
		{"DENYLIST_<KIND>", "A deny-list entry matched; risk forced to 100"},
		{"ALWAYS_CHALLENGE_<KIND>", "An always-challenge entry matched"},
		{"MODEL_ANOMALY", "The learned anomaly model added risk (at most 40, never allow to block)"},
		{"MODEL:<feature>", "A feature that made the vector unusual for this site (explanation, weight 0)"},
		{"MODEL_SUPERVISED", "Shadow contribution of the supervised model before it is promoted"},
		{"CHALLENGE_SOLVED", "Proof of work solved (credit 20)"},
		{"VISUAL_CHALLENGE_SOLVED", "Visual or audio challenge solved (credit 45)"},
		{"VERIFIED_CRAWLER_<NAME>", "Edge mode: request from a published crawler range"},
	} {
		fmt.Fprintf(&b, "| `%s` | %s |\n", x[0], x[1])
	}
	must(os.WriteFile(filepath.Join(*out, "reason-codes.md"), []byte(b.String()), 0o644))
}

func unless(u string) string {
	if u == "" {
		return ""
	}
	return "`" + esc(u) + "`"
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
